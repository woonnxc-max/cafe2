/**
 * Supabase SQL Editor에 복사하여 실행할 수 있는 테이블 생성 및 테스트 데이터 INSERT 쿼리문
 */

// 1. [기본/권장] 기존 테이블을 안전하게 리셋 후 새로 생성하는 쿼리문
export const SUPABASE_SQL_SCRIPT = `-- =================================================================
-- [바이브 카페] Supabase SQL Editor 실행용 쿼리문
-- 원인: 이미 동일한 이름(cafe_menu)의 테이블이 다른 컬럼으로 생성되어 있어
--       CREATE TABLE IF NOT EXISTS 가 건너뛰어졌을 때 발생합니다.
-- 해결: 기존 테이블을 삭제(DROP)하고 주문서 항목에 맞게 새로 생성합니다.
-- =================================================================

-- 1. 기존 테이블 및 기존 정책 초기화 (충돌 방지)
DROP TABLE IF EXISTS public.cafe_menu CASCADE;

-- 2. 주문서 항목에 맞춘 cafe_menu 테이블 생성
CREATE TABLE public.cafe_menu (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 주문 고유 번호 (PK)
    customer_name TEXT NOT NULL,                           -- 주문자 이름 (필수, text)
    phone_number TEXT,                                     -- 전화번호 (tel, text)
    beverage TEXT NOT NULL,                                -- 음료 종류 (아메리카노, 카페라떼 등)
    size VARCHAR(5) NOT NULL DEFAULT 'M',                  -- 음료 사이즈 ('S', 'M', 'L')
    options TEXT[] DEFAULT '{}',                           -- 추가 옵션 배열 (샷 추가, 크림 추가 등)
    quantity INTEGER NOT NULL DEFAULT 1 CHECK (quantity >= 1 AND quantity <= 10), -- 수량 (1~10)
    requests TEXT,                                         -- 요청사항 (textarea)
    total_price INTEGER NOT NULL DEFAULT 0,                -- 총 예상 금액 (원 단위)
    status TEXT NOT NULL DEFAULT '접수',                   -- 주문 상태 ('접수', '제조중', '완료')
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL -- 주문 접수 일시
);

-- 3. 테이블 및 컬럼 코멘트 등록
COMMENT ON TABLE public.cafe_menu IS '바이브 카페 고객 주문서 및 주문 내역 테이블';
COMMENT ON COLUMN public.cafe_menu.customer_name IS '주문자 이름 (필수)';
COMMENT ON COLUMN public.cafe_menu.phone_number IS '주문자 전화번호';
COMMENT ON COLUMN public.cafe_menu.beverage IS '선택한 음료 메뉴명';
COMMENT ON COLUMN public.cafe_menu.size IS '선택한 사이즈 (S, M, L)';
COMMENT ON COLUMN public.cafe_menu.options IS '선택된 추가 옵션 목록 (TEXT 배열)';
COMMENT ON COLUMN public.cafe_menu.quantity IS '주문 수량 (최소 1, 최대 10)';
COMMENT ON COLUMN public.cafe_menu.requests IS '고객 특별 요청사항';
COMMENT ON COLUMN public.cafe_menu.total_price IS '총 계산 금액';
COMMENT ON COLUMN public.cafe_menu.status IS '주문 처리 상태';

-- 4. Supabase RLS (Row Level Security) 설정
ALTER TABLE public.cafe_menu ENABLE ROW LEVEL SECURITY;

-- 주문 등록(INSERT) 정책 허용
CREATE POLICY "누구나 주문 등록 가능" 
ON public.cafe_menu 
FOR INSERT 
TO public 
WITH CHECK (true);

-- 주문 내역(SELECT) 정책 허용
CREATE POLICY "누구나 주문 내역 조회 가능" 
ON public.cafe_menu 
FOR SELECT 
TO public 
USING (true);

-- 5. 테스트용 1건 가짜 데이터 INSERT 쿼리문
INSERT INTO public.cafe_menu (
    customer_name,
    phone_number,
    beverage,
    size,
    options,
    quantity,
    requests,
    total_price,
    status
) VALUES (
    '홍길동',
    '010-1234-5678',
    '카페라떼',
    'M',
    ARRAY['샷 추가'],
    1,
    '얼음 적게 부탁드립니다.',
    5000,
    '접수'
);

-- 6. 데이터가 정상적으로 들어갔는지 확인
SELECT * FROM public.cafe_menu ORDER BY created_at DESC LIMIT 5;
`;

